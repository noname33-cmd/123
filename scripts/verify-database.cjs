const {spawnSync} = require('node:child_process');
const {randomUUID} = require('node:crypto');
const path = require('node:path');

const image = 'postgis/postgis:17-3.5@sha256:01a6a70e41e6c4467c8f55f6063555ed72db2d6662cd0d571040d42eadaeb6f6';
const root = path.resolve(__dirname, '..');

function docker(args, allowFailure = false) {
  const result = spawnSync('docker', args, {encoding: 'utf8', timeout: 180000});
  if (result.error || result.status !== 0) {
    if (allowFailure) {return null;}
    // Commands may contain the temporary password; never print their arguments.
    throw new Error('Docker database test command failed; check Docker availability and image access');
  }
  return result.stdout.trim();
}

function databaseUrl(mapping, password) {
  const match = /^127\.0\.0\.1:(\d+)$/.exec(mapping);
  const port = Number(match?.[1]);
  if (!match || port < 1 || port > 65535) {
    throw new Error('Expected one ephemeral IPv4 loopback database port');
  }
  const url = new URL(`postgresql://truck@127.0.0.1:${port}/truck_route_savings`);
  url.password = password;
  return url.toString();
}

function runTests(url) {
  const result = spawnSync(process.execPath, [require.resolve('jest/bin/jest'),
    '--config', path.join(root, 'apps/api/jest.config.cjs'), '--runInBand',
    '--testPathPattern=integration', '--detectOpenHandles'], {
    cwd: root, env: {...process.env, DATABASE_URL: url}, stdio: 'inherit', timeout: 120000,
  });
  if (result.error || result.status !== 0) {throw new Error('Database integration tests failed');}
  const smoke = spawnSync(process.execPath, [path.join(__dirname, 'verify-api-database.cjs')], {
    cwd: root, env: {...process.env, DATABASE_URL: url}, stdio: 'inherit', timeout: 30000,
  });
  if (smoke.error || smoke.status !== 0) {throw new Error('Compiled API database smoke failed');}
}

async function verifyDatabase({run = docker, test = runTests,
  pause = () => new Promise(resolve => setTimeout(resolve, 1000))} = {}) {
  const name = `truck-db-integration-${randomUUID()}`;
  const password = randomUUID();
  // A unique container and anonymous volume: never use an existing developer database.
  // Pull separately so a slow download cannot leave a timed-out run with an unknown ID.
  run(['pull', image]);
  try {
    run(['run', '--detach', '--rm', '--name', name,
      '--env', 'POSTGRES_USER=truck', '--env', 'POSTGRES_DB=truck_route_savings',
      '--env', `POSTGRES_PASSWORD=${password}`, '--publish', '127.0.0.1::5432', image]);
    let ready = false;
    for (let attempt = 0; attempt < 45; attempt++) {
      if (run(['exec', name, 'pg_isready', '-h', '127.0.0.1', '-U', 'truck',
        '-d', 'truck_route_savings'], true) !== null) {ready = true; break;}
      await pause();
    }
    if (!ready) {throw new Error('Temporary PostgreSQL did not become ready');}
    test(databaseUrl(run(['port', name, '5432/tcp']), password));
  } finally {
    // Only the name generated by this invocation can be removed, including on startup failure.
    run(['rm', '--force', '--volumes', name]);
  }
  return 'Real Nest/Prisma/PostGIS connection, password rejection and shutdown checks passed; temporary database removed.';
}

module.exports = {databaseUrl, verifyDatabase};
if (require.main === module) {
  verifyDatabase().then(message => console.log(message)).catch(error => {
    console.error(error.message); process.exitCode = 1;
  });
}
